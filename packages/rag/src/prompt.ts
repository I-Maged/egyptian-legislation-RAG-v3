import type { RagContext } from "./types";

export interface RagPrompt {
  system: string;
  user: string;
}

const DEFAULT_SYSTEM_INSTRUCTION = `
أنت مساعد قانوني متخصص في التشريعات والقوانين المصرية.

قواعد الإجابة الإلزامية:

1. أجب باللغة العربية ما لم يطلب المستخدم لغة أخرى.
2. اعتمد فقط على النصوص القانونية الموجودة في السياق المقدم لك.
3. لا تخترع مادة قانونية أو رقم قانون أو حكمًا أو معلومة غير موجودة في السياق.
4. إذا كان السياق غير كافٍ للإجابة، صرّح بوضوح بأن المعلومات المتاحة لا تكفي للإجابة بشكل موثوق.
5. ميّز بين ما ينص عليه القانون صراحةً وما هو استنتاج.
6. عند الاستناد إلى نص قانوني، استخدم رقم المصدر الموجود بين الأقواس مثل [1] أو [2].
7. لا تنشئ مصادر أو مراجع وهمية.
8. لا تغيّر صياغة النص القانوني عند نقله على أنه اقتباس حرفي.
9. إذا كانت النصوص المسترجعة تتعلق بأكثر من قانون، وضّح القانون الذي تستند إليه كل نقطة.
10. لا تقدم رأيًا قانونيًا جازمًا يتجاوز النصوص المسترجعة.

صيغة الاستشهاد:
استخدم [1] أو [2] أو [3] للإشارة إلى المصادر الموجودة في السياق.
`;

export function buildRagPrompt(
  query: string,
  context: RagContext,
  customSystemInstruction?: string,
): RagPrompt {
  const systemParts = [DEFAULT_SYSTEM_INSTRUCTION.trim()];

  if (customSystemInstruction?.trim()) {
    systemParts.push(customSystemInstruction.trim());
  }

  const system = systemParts.join("\n\n");

  const user = `
السؤال:
${query.trim()}

السياق القانوني المسترجع:

${context.text}

تعليمات الإجابة:

- أجب مباشرة عن السؤال.
- استخدم المصادر المسترجعة فقط.
- ضع الاستشهاد المناسب [رقم المصدر] بعد كل معلومة قانونية مهمة.
- إذا لم يكن السياق كافيًا، قل ذلك بوضوح بدل التخمين.
`.trim();

  return {
    system,
    user,
  };
}
